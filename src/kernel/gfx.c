// 设置 256 色调色板（仅 8bpp 模式使用）
void gfx_set_palette(void) {
    static const uint8_t std_r[16] = {0,0,0,0,170,170,170,170,85,85,85,85,255,255,255,255};
    static const uint8_t std_g[16] = {0,0,170,170,0,0,170,170,85,85,255,255,85,85,255,255};
    static const uint8_t std_b[16] = {0,170,0,170,0,170,0,170,85,255,85,255,85,255,85,255};
    outb(0x3C8, 0);
    for (int i = 0; i < 256; i++) {
        uint8_t r, g, b;
        if (i < 16) {
            r = std_r[i]; g = std_g[i]; b = std_b[i];
        } else {
            r = (uint8_t)((i * 3) & 0x3F);
            g = (uint8_t)((i * 5) & 0x3F);
            b = (uint8_t)((i * 7) & 0x3F);
        }
        outb(0x3C9, r); outb(0x3C9, g); outb(0x3C9, b);
    }
}

// 加载 8x8 字体（使用内置字体，不读 ROM）
void gfx_load_font(void) {
    int n = (int)(sizeof(builtin_font) / sizeof(builtin_font[0]));
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < 8; j++) {
            font8x8[i][j] = builtin_font[i][j];
        }
    }
    for (int i = 128; i < 256; i++) {
        for (int j = 0; j < 8; j++) {
            font8x8[i][j] = 0;
        }
    }
}

// 初始化图形模式：VBE 优先，回退 VGA 0x13
void gfx_init(void) {
    vbe_info_t info;
    gfx_read_vbe_info(&info);

    if (info.vbe_ok && info.fb_addr != 0 && info.width > 0 && info.height > 0) {
        // VBE 线性帧缓冲模式
        GFX_W = info.width;
        GFX_H = info.height;
        GFX_BPP = info.bpp;
        GFX_FB = info.fb_addr;
        GFX_PITCH = (info.pitch != 0) ? info.pitch : (info.width * (info.bpp / 8));
        if (GFX_BPP == 8) {
            gfx_set_palette();
        }
    } else {
        // 回退 VGA 0x13
        vga13_init();
        GFX_W = 320;
        GFX_H = 200;
        GFX_BPP = 8;
        GFX_FB = 0xA0000;
        GFX_PITCH = 320;
        gfx_set_palette();
    }
    gfx_load_font();
    mouse_set_bounds(GFX_W, GFX_H);
}

// 写一个像素，支持 32/24/16/8 bpp
void gfx_putpixel(int x, int y, uint32_t color) {
    if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H) return;
    uint8_t *base = (uint8_t*)GFX_FB;
    uint8_t *p = base + (uint32_t)y * (uint32_t)GFX_PITCH + (uint32_t)x * (uint32_t)(GFX_BPP / 8);
    switch (GFX_BPP) {
        case 32:
            p[0] = (uint8_t)(color & 0xFF);
            p[1] = (uint8_t)((color >> 8) & 0xFF);
            p[2] = (uint8_t)((color >> 16) & 0xFF);
            p[3] = 0;
            break;
        case 24:
            p[0] = (uint8_t)(color & 0xFF);
            p[1] = (uint8_t)((color >> 8) & 0xFF);
            p[2] = (uint8_t)((color >> 16) & 0xFF);
            break;
        case 16: {
            uint16_t c = (uint16_t)(((color & 0xF80000) >> 8) | ((color & 0x00FC00) >> 5) | ((color & 0x0000F8) >> 3));
            p[0] = (uint8_t)(c & 0xFF);
            p[1] = (uint8_t)(c >> 8);
            break;
        }
        case 8:
        default:
            p[0] = (uint8_t)(color & 0xFF);
            break;
    }
}

void gfx_fill_rect(int x, int y, int w, int h, uint32_t color) {
    for (int j = 0; j < h; j++) {
        for (int i = 0; i < w; i++) {
            gfx_putpixel(x + i, y + j, color);
        }
    }
}

void gfx_draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int i = 0; i < w; i++) {
        gfx_putpixel(x + i, y, color);
        gfx_putpixel(x + i, y + h - 1, color);
    }
    for (int j = 0; j < h; j++) {
        gfx_putpixel(x, y + j, color);
        gfx_putpixel(x + w - 1, y + j, color);
    }
}

void gfx_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    uint8_t ch = (uint8_t)c;
    for (int row = 0; row < 8; row++) {
        uint8_t line = font8x8[ch][row];
        for (int col = 0; col < 8; col++) {
            gfx_putpixel(x + col, y + row, (line & (0x80 >> col)) ? fg : bg);
        }
    }
}

void gfx_draw_text(int x, int y, const char *s, uint32_t fg, uint32_t bg) {
    while (*s) {
        gfx_draw_char(x, y, *s, fg, bg);
        x += 8;
        s++;
    }
}

void gfx_clear(uint32_t color) {
    gfx_fill_rect(0, 0, GFX_W, GFX_H, color);
}
