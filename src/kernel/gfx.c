// 从 0x5000 读取 VBE 结果
void gfx_read_vbe_info(vbe_info_t *info) {
    uint8_t *p = (uint8_t*)0x5000;
    info->fb_addr = *(uint32_t*)(p + 0);
    info->width   = *(uint16_t*)(p + 4);
    info->height  = *(uint16_t*)(p + 6);
    info->bpp     = *(uint8_t*)(p + 8);
    info->vbe_ok  = *(uint8_t*)(p + 9);
    info->pitch   = *(uint16_t*)(p + 10);
}

